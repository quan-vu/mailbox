//! Secret-store port (MB-113). Secrets are addressed by an opaque reference that is safe to
//! store in the database (`accounts.credential_ref`); the secret value itself never is.
use crate::MailboxError;

/// A secret value. It cannot be printed, compared or serialized, and its memory is overwritten
/// when dropped. Read it only at the point of use with [`Secret::expose`].
pub struct Secret(String);

impl Secret {
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Borrow the value for immediate use (e.g. an IMAP LOGIN). Do not copy it into owned strings.
    pub fn expose(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Debug for Secret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("Secret(<redacted>)")
    }
}

impl Drop for Secret {
    fn drop(&mut self) {
        // SAFETY: zero bytes are valid UTF-8, so the String stays valid while being cleared.
        for byte in unsafe { self.0.as_bytes_mut() } {
            // Volatile write so the compiler cannot drop the wipe as a dead store.
            unsafe { std::ptr::write_volatile(byte, 0) };
        }
    }
}

/// References are generated by the application, never taken from user input.
pub fn is_valid_reference(reference: &str) -> bool {
    !reference.is_empty()
        && reference.len() <= 128
        && reference
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ':' | '.'))
}

pub trait SecretStore {
    /// Store or replace the secret for `reference`.
    fn put(&self, reference: &str, secret: &Secret) -> Result<(), MailboxError>;
    /// `MailboxError::NotFound` when nothing is stored (e.g. the user removed it): the account
    /// then needs re-authentication.
    fn get(&self, reference: &str) -> Result<Secret, MailboxError>;
    /// Deleting a missing entry succeeds, so account removal is idempotent.
    fn delete(&self, reference: &str) -> Result<(), MailboxError>;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn secret_is_redacted_in_debug_output() {
        let secret = Secret::new("app-password-123");
        assert_eq!(format!("{secret:?}"), "Secret(<redacted>)");
        assert_eq!(secret.expose(), "app-password-123");
    }

    #[test]
    fn references_are_restricted_to_a_safe_alphabet() {
        assert!(is_valid_reference("keychain:acc-01.imap"));
        for bad in ["", "a b", "a/b", "a\nb", "x'; DROP", &"x".repeat(129)] {
            assert!(!is_valid_reference(bad), "{bad:?} should be rejected");
        }
    }
}
